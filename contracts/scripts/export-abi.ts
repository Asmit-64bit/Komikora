/**
 * Exports the ConsentCraftMarket ABI from the compiled artifact:
 *   abi/ConsentCraftMarket.json   plain JSON ABI for any client
 *   abi/ConsentCraftMarket.ts     `as const` ABI for typed viem/wagmi usage
 *
 *   npm run abi:export   (compiles first). A test fails if the committed ABI drifts.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(
  readFileSync("artifacts/contracts/ConsentCraftMarket.sol/ConsentCraftMarket.json", "utf8"),
) as { abi: unknown[] };

mkdirSync("abi", { recursive: true });
const json = JSON.stringify(artifact.abi, null, 2);
writeFileSync("abi/ConsentCraftMarket.json", `${json}\n`);
writeFileSync(
  "abi/ConsentCraftMarket.ts",
  `// Generated by scripts/export-abi.ts from the compiled artifact. Do not edit.\nexport const consentCraftMarketAbi = ${json} as const;\n`,
);
console.log(`Exported ${artifact.abi.length} ABI entries to abi/ConsentCraftMarket.{json,ts}`);
